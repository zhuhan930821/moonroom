import { test, expect } from '@playwright/test'

test('guitar can be approached, recorded, strummed and exited', async ({ page }) => {
  test.setTimeout(180000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5190/?demo=1&capture=1&whiteModel=1&spawn=guitar', { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => window.__moonroomGame?.started)
  await page.waitForFunction(() => window.__moonroomGame?.near === 'guitar')
  await page.keyboard.press('e')
  await expect(page.getByTestId('guitar-controls')).toBeVisible()
  await page.keyboard.press('3')
  await expect(page.getByTestId('guitar-controls')).toContainText('Am')
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('guitar-controls')).toHaveAttribute('data-recording', '1')
  await page.keyboard.press('Space')
  await page.waitForFunction(() => window.__moonroomGame?.guitarHit > 0)
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => window.__moonroomGame?.lastTake?.events.some(event => event.pad === 'guitar'))
  await expect(page.getByTestId('guitar-controls')).toHaveAttribute('data-recording', '0')
  await page.keyboard.press('Escape')
  await expect(page.locator('main')).toHaveAttribute('data-mode', 'explore')
  const guitarName = await page.evaluate(() => window.__moonroomGame.lastTake.name)
  await page.evaluate(() => window.__moonroomGame.enter('computer'))
  await page.getByTestId('icon-studio').click()
  await expect(page.getByTestId('studio-window')).toBeVisible()
  await page.getByRole('button', { name: '+ Drums' }).click()
  await page.getByLabel('选择要叠加的作品').selectOption({ label: guitarName })
  await page.getByRole('button', { name: '叠加轨道' }).click()
  await expect(page.locator('.studio-lane.guitar').first()).toBeVisible()
  await expect(page.locator('.studio-lane').filter({ has: page.getByText('Kick', { exact: true }) })).toBeVisible()
  await page.locator('.studio-lane').filter({ has: page.getByText('Kick', { exact: true }) }).locator('.lane-track').click({ position: { x: 8, y: 8 } })
  await page.getByRole('button', { name: '+ Piano' }).click()
  const pianoName = await page.locator('.studio-item.active strong').textContent()
  await page.locator('.studio-lane.piano').first().locator('.lane-track').click({ position: { x: 8, y: 8 } })
  await page.locator('.studio-item').filter({ hasText: 'Drums' }).click()
  await page.getByLabel('选择要叠加的作品').selectOption({ label: pianoName })
  await page.getByRole('button', { name: '叠加轨道' }).click()
  await expect(page.locator('.studio-lane.piano').first()).toBeVisible()
  await page.getByTestId('studio-play').click()
  await expect(page.getByTestId('studio-play')).toContainText('Stop')
  await page.getByTestId('studio-play').click()
  const downloadPromise = page.waitForEvent('download', { timeout: 120000 })
  await page.getByRole('button', { name: /Export WAV/ }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/\.wav$/)
  expect(errors).toEqual([])
})

test('mobile string swipe records amplified chords and keeps the red tone', async ({ page }) => {
  test.setTimeout(120000)
  await page.goto('http://127.0.0.1:5190/?demo=1&capture=1&whiteModel=1&mobile=1&spawn=guitar', { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => window.__moonroomGame?.started)
  await page.evaluate(() => window.__moonroomGame.enter('guitar'))
  await page.getByRole('button', { name: '接音箱' }).click()
  await page.getByRole('button', { name: '4 · F' }).click()
  await page.getByTestId('guitar-record').click()
  const strings = page.getByRole('button', { name: '划过六根弦扫和弦' })
  const bounds = await strings.boundingBox()
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + 18)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height - 18, { steps: 8 })
  await page.mouse.up()
  await page.getByTestId('guitar-record').click()
  await page.waitForFunction(() => window.__moonroomGame?.lastTake?.events.some(event => event.pad === 'guitar' && event.tone === 'electric'))
})
